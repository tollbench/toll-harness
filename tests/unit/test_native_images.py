PNG = b"\x89PNG\r\n\x1a\nactual generated bytes"


@pytest.fixture
def native(tmp_path, monkeypatch):
    monkeypatch.setenv("CODEX_HOME", str(tmp_path / "codex"))
    thread = str(uuid4())
    directory = tmp_path / "codex" / "generated_images" / thread
    directory.mkdir(parents=True)
    image = directory / "exec-image.png"
    image.write_bytes(PNG)
    event = json.dumps({"type": "thread.started", "thread_id": thread})
    return directory, image, event


def test_only_cli_thread_images_are_collected(native):
    directory, image, event = native
    other = directory.parent / str(uuid4())
    other.mkdir()
    (other / "other.png").write_bytes(PNG)
    actual = collect_codex_images(event)
    assert len(actual) == 1
    assert actual[0].source_path == str(image)
    assert actual[0].content == PNG
    assert collect_codex_images(json.dumps({"text": str(image)})) == []
    assert collect_codex_images('{"type":"thread.started","thread_id":"../../etc"}') == []


def test_symlink_files_and_non_images_are_never_imported(native):
    directory, image, event = native
    image.unlink()
    outside = directory.parent / "private.png"
    outside.write_bytes(PNG)
    image.symlink_to(outside)
    (directory / "false.png").write_text("not an image")
    (directory / "document.txt").write_bytes(PNG)
    assert collect_codex_images(event) == []


def test_symlink_thread_directory_is_never_imported(native):
    directory, image, event = native
    image.unlink()
    directory.rmdir()
    outside = directory.parent / "outside"
    outside.mkdir()
    (outside / image.name).write_bytes(PNG)
    directory.symlink_to(outside, target_is_directory=True)
    assert collect_codex_images(event) == []


def test_image_size_limit(native, monkeypatch):
    _, _, event = native
    monkeypatch.setattr("toll_harness.models.native_images.MAX_IMAGE_BYTES", len(PNG) - 1)
    assert collect_codex_images(event) == []


def test_codex_response_carries_images_and_clears_them_between_calls(native, tmp_path):
    _, image, event = native
    events = [event, ""]

    def run(argv, **kwargs):
        Path(argv[argv.index("--output-last-message") + 1]).write_text('{"text":"done"}')
        return SimpleNamespace(returncode=0, stdout=events.pop(0), stderr="")

    adapter = CodexCliAdapter(workdir=tmp_path / "cli", runner=run)
    first = adapter.invoke(system="", messages=[], tools=[])
    assert first.artifacts[0].source_path == str(image)
    assert adapter.invoke(system="", messages=[], tools=[]).artifacts == ()


def response(*calls, artifacts=()):
    return ModelResponse(
        message=ModelMessage.text("assistant", "generated"),
        text="generated",
        tool_calls=[ToolCall(str(i), name, args) for i, (name, args) in enumerate(calls)],
        artifacts=artifacts,
    )


def test_native_file_delivery_uses_imported_bytes_and_does_not_relax_paths(tmp_path):
    delivered = []
    provider = SimpleNamespace(
        deliver_file=lambda deal, **data: delivered.append(data) or {"ok": True}
    )
    store = SQLiteStore(tmp_path / "db")
    artifacts = FilesystemArtifactStore(tmp_path / "artifacts")
    registry = build_standard_registry()
    add_toll_bench_tools(registry)
    source = "/outside/native/real.png"
    model = ScriptedModelAdapter(
        [
            response(
                ("toll_bench.deliver_file", {"deal_id": "deal", "path": source, "title": "Flyer"}),
                artifacts=(ModelArtifact(source, "real.png", PNG),),
            ),
            response(("human.request", {"question": "Review flyer"})),
        ]
    )
    runtime = HarnessRuntime(
        model=model,
        state_store=store,
        event_store=store,
        artifact_store=artifacts,
        tools=registry,
        enabled_tools=["toll_bench.deliver_file", "result.complete", "human.request"],
        toll_bench_provider=provider,
    )
    result = runtime.start("deliver real flyer")
    assert delivered[0]["content"] == PNG
    assert artifacts.read(result.run_id, "generated/real.png") == PNG
    events = [e for e in store.list_events(result.run_id) if e.kind == "model.artifact"]
    assert len(events) == 1 and events[0].payload["source_path"] == source
    with pytest.raises(ValueError, match="escapes"):
        artifacts.read(result.run_id, source)
    with pytest.raises(ValueError, match="escapes"):
        artifacts.read(result.run_id, "/outside/private.png")
    # Resume retains the exact runtime-created alias; it does not reopen the source.
    runtime.model = ScriptedModelAdapter(
        [
            response(
                ("toll_bench.deliver_file", {"deal_id": "deal", "path": source, "title": "Again"})
            ),
            response(("result.complete", {"summary": "delivered again"})),
        ]
    )
    runtime.resume(result.run_id)
    assert len(delivered) == 2 and delivered[1]["content"] == PNG


def test_rejected_source_path_does_not_call_provider(tmp_path):
    from toll_harness.tools.registry import ToolContext

    delivered = []
    registry = build_standard_registry()
    add_toll_bench_tools(registry)
    store = SQLiteStore(tmp_path / "db")
    context = ToolContext(
        "run1",
        store,
        store,
        FilesystemArtifactStore(tmp_path / "artifacts"),
        0,
        toll_bench_provider=SimpleNamespace(deliver_file=lambda *a, **kw: delivered.append(kw)),
    )
    answer = registry.execute(
        context,
        "x",
        "toll_bench.deliver_file",
        {
            "deal_id": "deal",
            "path": "/outside/private.png",
            "title": "private",
        },
    )
    assert answer.is_error and not delivered
    assert "escapes" in str(answer.output)
